// Bundles webengine/engine.js (Tilawa + onnxruntime-web) into one HTML page for the app's hidden WebView, and copies
// onnxruntime-web's WASM binary into assets/engine/. Output: src/engine/generated/engine-html.ts.
import { build } from "esbuild";
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";

const root = new URL("..", import.meta.url).pathname;
const res = await build({
  entryPoints: [root + "webengine/engine.js"],
  bundle: true,
  format: "esm",
  platform: "browser",
  target: "chrome100",
  minify: true,
  write: false,
  legalComments: "eof",
  logLevel: "warning",
});
const js = res.outputFiles[0].text.replace(/<\/script/gi, "<\\/script");
const html = `<!doctype html><html><head><meta charset="utf-8"><title>Tilawa engine</title></head><body><script type="module">${js}</script></body></html>`;
mkdirSync(root + "src/engine/generated", { recursive: true });
writeFileSync(
  root + "src/engine/generated/engine-html.ts",
  `// Generated by scripts/build-engine.mjs. Do not edit.\n// Contains @tilawa/core (MIT) and onnxruntime-web (MIT); see NOTICE.md.\nexport const ENGINE_HTML = ${JSON.stringify(html)};\n`,
);
mkdirSync(root + "assets/engine", { recursive: true });
const ortDir = root + "node_modules/onnxruntime-web/dist/";
// Metro bundles it as an asset; the ".bin" extension keeps it a plain binary resource.
copyFileSync(ortDir + "ort-wasm-simd-threaded.wasm", root + "assets/engine/ort-wasm-simd-threaded.wasm.bin");
const version = JSON.parse(readFileSync(root + "node_modules/onnxruntime-web/package.json", "utf8")).version;
console.log(`engine page ${(html.length / 1024).toFixed(0)} KB, onnxruntime-web ${version}`);
